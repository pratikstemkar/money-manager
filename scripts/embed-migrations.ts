/**
 * Reads drizzle/*.sql and inlines it into a TypeScript module so the browser
 * build can apply migrations without filesystem access.
 *
 * Run with: bun scripts/embed-migrations.ts
 */
interface JournalEntry {
  idx: number;
  tag: string;
}

const journal = (await Bun.file("drizzle/meta/_journal.json").json()) as {
  entries: JournalEntry[];
};

const migrations: { version: number; sql: string }[] = [];

for (const entry of [...journal.entries].sort((a, b) => a.idx - b.idx)) {
  const sql = await Bun.file(`drizzle/${entry.tag}.sql`).text();
  migrations.push({ version: entry.idx + 1, sql });
}

const content = `/**
 * AUTO-GENERATED by scripts/embed-migrations.ts — do not edit by hand.
 * Regenerate after \`bun run db:generate\`.
 */
export const MIGRATIONS: { version: number; sql: string }[] = ${JSON.stringify(
  migrations,
  null,
  2,
)};
`;

await Bun.write("lib/db/migrations.generated.ts", content);
console.log(`Embedded ${migrations.length} migration(s).`);

export {};
