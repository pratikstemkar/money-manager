function toCsv(matrix: (string | number)[][]): string {
  return (
    matrix
      .map((row) =>
        row
          .map((value) => {
            const text = String(value);
            return /[",\n]/.test(text)
              ? `"${text.replace(/"/g, '""')}"`
              : text;
          })
          .join(","),
      )
      .join("\n") + "\n"
  );
}

